/**
 * キースイッチの斜め見下ろしアイコン。ハウジングは無彩色、軸だけ赤・青・茶に色分け。
 * 上ハウジングは半透明なので、その下に隠れる下ハウジングの線・塗りは薄く描いて透け感を出す。
 */
function switchAvatar(axis: keyof typeof SWITCH_STEM_COLORS, bg = '#faf7f0'): string {
  const stemColors = SWITCH_STEM_COLORS[axis]
  const layer = (d: string, fill: string, strokeWidth: number, fillOpacity = 1, strokeOpacity = 1) =>
    `<path d="${d}" fill="${fill}" fill-opacity="${fillOpacity}" fill-rule="evenodd" `
    + `stroke="#111111" stroke-opacity="${strokeOpacity}" stroke-width="${strokeWidth}" stroke-linejoin="round"/>`

  // 上ハウジングの下に隠れる部分: 線も塗りも薄くして透け感を出す
  const bottomHidden = SWITCH_BOTTOM_HOUSING_HIDDEN_PATHS
    .map((p) => layer(p.d, SWITCH_BOTTOM_HOUSING_COLORS[p.shade], 0.7, 0.45, 0.4))
    .join('')
  const bottomVisible = SWITCH_BOTTOM_HOUSING_VISIBLE_PATHS
    .map((p) => layer(p.d, SWITCH_BOTTOM_HOUSING_COLORS[p.shade], 1.5))
    .join('')
  // 上ハウジング本体: 半透明なクリアパーツなので塗りだけ落とし、輪郭線はくっきり保つ
  const topHousing = SWITCH_TOP_HOUSING_PATHS
    .map((p) => layer(p.d, SWITCH_TOP_HOUSING_COLORS[p.shade], 1.5, 0.72, 1))
    .join('')
  const stem = SWITCH_STEM_PATHS
    .map((p) => layer(p.d, stemColors[p.shade], 1.5))
    .join('')

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">`
    + `<rect x="4" y="4" width="56" height="56" rx="14" fill="${bg}" stroke="#111111" stroke-width="4"/>`
    + bottomHidden + bottomVisible + topHousing + stem + `</svg>`
  return `data:image/svg+xml,${encodeURIComponent(svg)}`
}

