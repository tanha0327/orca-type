/** キースイッチの斜め見下ろしアイコン（ハウジングは無彩色、軸だけ赤・青・茶に色分け） */
function switchAvatar(axis: keyof typeof SWITCH_STEM_COLORS, bg = '#faf7f0'): string {
  const stemColors = SWITCH_STEM_COLORS[axis]
  const layer = (d: string, fill: string) =>
    `<path d="${d}" fill="${fill}" fill-rule="evenodd" stroke="#111111" stroke-width="1.5" stroke-linejoin="round"/>`
  const housing = SWITCH_HOUSING_PATHS
    .map((p) => layer(p.d, SWITCH_HOUSING_COLORS[p.part][p.shade]))
    .join('')
  const stem = SWITCH_STEM_PATHS
    .map((p) => layer(p.d, stemColors[p.shade]))
    .join('')
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">`
    + `<rect x="4" y="4" width="56" height="56" rx="14" fill="${bg}" stroke="#111111" stroke-width="4"/>`
    + housing + stem + `</svg>`
  return `data:image/svg+xml,${encodeURIComponent(svg)}`
}

